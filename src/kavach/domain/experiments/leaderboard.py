from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime


@dataclass(frozen=True)
class LeaderboardEntry:
    """
    Ranked experiment candidate snapshot generated by the ranking engine.
    """

    rank: int
    candidate_id: str
    overall_score: float
    metrics: dict[str, float]
    cost: float | None
    latency: float | None
    reason: str

    def __post_init__(self) -> None:
        if self.rank <= 0:
            raise ValueError("LeaderboardEntry rank must be greater than zero.")

        if not self.candidate_id.strip():
            raise ValueError(
                "LeaderboardEntry candidate_id must not be empty."
            )

        if not self.reason.strip():
            raise ValueError("LeaderboardEntry reason must not be empty.")

        object.__setattr__(self, "metrics", dict(self.metrics))


@dataclass(frozen=True)
class Leaderboard:
    """
    Immutable experiment ranking snapshot for governance decisions.
    """

    leaderboard_id: str
    experiment_id: str
    ranking_strategy: str
    generated_at: datetime
    entries: tuple[LeaderboardEntry, ...]

    def __post_init__(self) -> None:
        if not self.leaderboard_id.strip():
            raise ValueError("Leaderboard leaderboard_id must not be empty.")

        if not self.experiment_id.strip():
            raise ValueError("Leaderboard experiment_id must not be empty.")

        if not self.ranking_strategy.strip():
            raise ValueError("Leaderboard ranking_strategy must not be empty.")

        object.__setattr__(self, "entries", tuple(self.entries))

        ranks = [entry.rank for entry in self.entries]
        if ranks and ranks != list(range(1, len(self.entries) + 1)):
            raise ValueError(
                "Leaderboard entries must use consecutive ranks starting at one."
            )
