#!/usr/bin/env bash

set -euo pipefail

# Resolve repository root
REPO_ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
cd "$REPO_ROOT"

# Build metadata. Source snapshots and freshly initialized local worktrees may
# not have a HEAD commit yet; they are still valid inputs for a local Compose
# boot and must not prevent the platform from starting.
if git rev-parse --verify HEAD >/dev/null 2>&1; then
    COMMIT_SHA="$(git rev-parse --short HEAD)"
    COMMIT_SHA_FULL="$(git rev-parse HEAD)"
    if [[ -n "$(git status --porcelain)" ]]; then
        BUILD_DIRTY="true"
    else
        BUILD_DIRTY="false"
    fi
else
    COMMIT_SHA="local"
    COMMIT_SHA_FULL="local-source-snapshot"
    BUILD_DIRTY="true"
fi
BUILD_DATE="$(date -u +"%Y-%m-%dT%H:%M:%SZ")"

BUILD_FILE=".env.build"

cat > "$BUILD_FILE" <<EOF
# -----------------------------------------------------------------------------
# Auto-generated build metadata.
# Generated by generate-build-metadata.sh
# Do not edit manually.
# -----------------------------------------------------------------------------

KAVACH_COMMIT_SHA=$COMMIT_SHA
KAVACH_COMMIT_SHA_FULL=$COMMIT_SHA_FULL
KAVACH_BUILD_DATE=$BUILD_DATE
KAVACH_BUILD_DIRTY=$BUILD_DIRTY
EOF

echo "Generated $BUILD_FILE"
echo
cat "$BUILD_FILE"
